CREATE TABLE IF NOT EXISTS workers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    skill TEXT NOT NULL,
    location TEXT NOT NULL,
    experience INTEGER NOT NULL CHECK (experience >= 0),
    wage INTEGER NOT NULL CHECK (wage >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    availability TEXT NOT NULL DEFAULT 'Immediate',
    rating REAL,
    password_hash TEXT,
    phone TEXT
);

ALTER TABLE workers ADD COLUMN IF NOT EXISTS phone TEXT;

CREATE INDEX IF NOT EXISTS idx_workers_email ON workers(email);
CREATE INDEX IF NOT EXISTS idx_workers_skill ON workers(skill);
CREATE INDEX IF NOT EXISTS idx_workers_location ON workers(location);

CREATE TABLE IF NOT EXISTS employers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    employer_type TEXT NOT NULL,
    location TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    password_hash TEXT,
    is_verified INTEGER NOT NULL DEFAULT 0,
    phone TEXT
);

ALTER TABLE employers ADD COLUMN IF NOT EXISTS phone TEXT;

CREATE INDEX IF NOT EXISTS idx_employers_email ON employers(email);
CREATE INDEX IF NOT EXISTS idx_employers_location ON employers(location);

CREATE TABLE IF NOT EXISTS jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employer_id BIGINT NOT NULL REFERENCES employers(id),
    title TEXT NOT NULL,
    skill_required TEXT NOT NULL,
    description TEXT NOT NULL,
    location TEXT NOT NULL,
    workers_needed INTEGER NOT NULL CHECK (workers_needed > 0),
    daily_wage INTEGER NOT NULL CHECK (daily_wage >= 0),
    status TEXT NOT NULL DEFAULT 'Open',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    positions_remaining INTEGER NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS idx_jobs_employer_id ON jobs(employer_id);
CREATE INDEX IF NOT EXISTS idx_jobs_status ON jobs(status);
CREATE INDEX IF NOT EXISTS idx_jobs_location ON jobs(location);
CREATE INDEX IF NOT EXISTS idx_jobs_skill_required ON jobs(skill_required);
CREATE INDEX IF NOT EXISTS idx_jobs_status_created_at ON jobs(status, created_at DESC);

CREATE TABLE IF NOT EXISTS applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id BIGINT NOT NULL REFERENCES workers(id),
    job_id BIGINT NOT NULL REFERENCES jobs(id),
    status TEXT NOT NULL DEFAULT 'Pending',
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (worker_id, job_id)
);

CREATE INDEX IF NOT EXISTS idx_applications_job_id ON applications(job_id);
CREATE INDEX IF NOT EXISTS idx_applications_worker_id ON applications(worker_id);
CREATE INDEX IF NOT EXISTS idx_applications_job_status ON applications(job_id, status);

CREATE TABLE IF NOT EXISTS saved_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id BIGINT NOT NULL REFERENCES workers(id),
    job_id BIGINT NOT NULL REFERENCES jobs(id),
    saved_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (worker_id, job_id)
);

CREATE INDEX IF NOT EXISTS idx_saved_jobs_worker_id ON saved_jobs(worker_id);
CREATE INDEX IF NOT EXISTS idx_saved_jobs_job_id ON saved_jobs(job_id);

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_role TEXT NOT NULL,
    user_id BIGINT NOT NULL,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    link TEXT,
    is_read INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notification_type TEXT DEFAULT 'JOB_POSTED',
    job_id BIGINT,
    company_name TEXT,
    job_title TEXT,
    location TEXT
);

CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_role, user_id);
CREATE INDEX IF NOT EXISTS idx_notifications_created_at ON notifications(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_job_type ON notifications(job_id, notification_type, user_role);

CREATE TABLE IF NOT EXISTS interviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES jobs(id),
    application_id BIGINT NOT NULL REFERENCES applications(id),
    employer_id BIGINT NOT NULL REFERENCES employers(id),
    worker_id BIGINT NOT NULL REFERENCES workers(id),
    interview_date TEXT NOT NULL,
    interview_time TEXT NOT NULL,
    location_or_link TEXT NOT NULL,
    notes TEXT,
    status TEXT NOT NULL DEFAULT 'Scheduled',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_interviews_worker_id ON interviews(worker_id);
CREATE INDEX IF NOT EXISTS idx_interviews_employer_id ON interviews(employer_id);
CREATE INDEX IF NOT EXISTS idx_interviews_job_id ON interviews(job_id);

CREATE TABLE IF NOT EXISTS reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_role TEXT NOT NULL,
    reporter_id BIGINT NOT NULL,
    target_type TEXT NOT NULL,
    target_id BIGINT NOT NULL,
    reason TEXT NOT NULL,
    details TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
